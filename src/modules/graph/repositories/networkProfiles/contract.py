from typing import Protocol

from modules.auth.domain.profile import Profile
from modules.graph.domain.catalogs import Catalogs


class NetworkProfileRepository(Protocol):
    def list_active(self) -> list[Profile]: ...
    def get_active(self, identifier: str) -> Profile | None: ...
    def by_reference(self, kind: str, identifier: str) -> list[Profile]: ...
    def catalogs(self, profiles: list[Profile]) -> Catalogs: ...
