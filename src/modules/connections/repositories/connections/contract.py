from typing import Protocol

from modules.connections.domain.connection import Connection


class ConnectionRepository(Protocol):
    def get(self, identifier: str) -> Connection | None: ...
    def find_pair(self, first: str, second: str) -> Connection | None: ...
    def list_for(self, identifier: str) -> list[Connection]: ...
    def accepted(self) -> list[Connection]: ...
    def count_accepted(self, identifier: str) -> int: ...
    def save(self, connection: Connection, insert: bool = False) -> None: ...
    def delete(self, identifier: str) -> None: ...
    def accept_pending(self, connection: Connection) -> bool: ...
