from typing import Protocol

from modules.auth.domain.user import User


class UserRepository(Protocol):
    def get(self, identifier: str) -> User | None: ...
    def find_email(self, email: str) -> User | None: ...
    def list_active(self) -> list[User]: ...
    def has_any(self) -> bool: ...
    def save(self, user: User, insert: bool = False) -> None: ...
    def delete(self, identifier: str) -> None: ...
    def lock_network(self, identifiers: list[str]) -> None: ...
