from typing import Protocol

from modules.auth.domain.research_project import ResearchProject


class ResearchProjectRepository(Protocol):
    def get(self, identifier: str) -> ResearchProject | None: ...
    def list(self) -> list[ResearchProject]: ...
    def get_many(self, identifiers: tuple[str, ...]) -> dict[str, dict]: ...
    def save(self, project: ResearchProject, insert: bool = False) -> None: ...
