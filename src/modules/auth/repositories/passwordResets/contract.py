from typing import Protocol

from modules.auth.domain.password_reset import PasswordReset


class PasswordResetRepository(Protocol):
    def get_hash(self, token_hash: str) -> PasswordReset | None: ...
    def latest_for_user(self, user_id: str) -> PasswordReset | None: ...
    def save(self, reset: PasswordReset) -> None: ...
    def delete(self, identifier: str) -> None: ...
    def delete_for_user(self, user_id: str) -> None: ...
